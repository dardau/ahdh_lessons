import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
// The app has only these three local modules. Emit a classic script so file://
// does not need module fetches, an HTTP server, or relaxed browser security.
const data = read('data.js').replace(/^export (?=const )/gm, '');
const logic = read('logic.js').replace(/^export (?=function )/gm, '');
const app = read('app.js').replace(/^import \{[^\n]+\} from '\.\/(?:data|logic)\.js';\r?\n/gm, '');
const bundle = '// Generated by npm run build. Edit app.js, data.js and logic.js.\n(function () {\n"use strict";\n' + data + '\n' + logic + '\n' + app + '\n})();\n';
fs.writeFileSync(path.join(root, 'app.bundle.js'), bundle);
fs.mkdirSync(path.join(root, 'dist'), {recursive:true});
for (const f of ['index.html', 'style.css', 'app.bundle.js']) {
  fs.copyFileSync(path.join(root, f), path.join(root, 'dist', f));
}
console.log('Ready: open index.html directly, or serve dist/');
